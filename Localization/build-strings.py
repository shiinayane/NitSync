#!/usr/bin/env python3
"""Generates Resources/<language>.lproj/Localizable.strings from translations.json.

Keys are the English text used in L("…") calls in Sources/ (English is the base language).
Fails, so the build fails, when a key used in the code has no translation, or a translation's
placeholders don't match its key's (count, type, numbering). Run by build.sh; run it by hand
to check after editing translations.json.
"""
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
LANGUAGES = ["ja", "zh-Hans", "zh-Hant"]

# %@, %ld, %1$@, %2$ld … (and %% which is not a placeholder).
SPEC = re.compile(r"%(?:(\d+)\$)?(@|ld|d|f|\.\d+f|%)")


def unsupported(text):
    """A % that isn't one of the specs above (e.g. %lld, %s, a lone %): not checked, so refused."""
    return re.sub(SPEC.pattern, "", text).count("%") > 0


def placeholders(text):
    found = []
    for i, m in enumerate(m for m in SPEC.finditer(text) if m.group(2) != "%"):
        found.append((int(m.group(1)) if m.group(1) else i + 1, m.group(2)))
    return sorted(found)


def source_keys():
    keys = []
    for path in sorted((ROOT / "Sources").glob("*.swift")):
        for m in re.finditer(r'\bL\("((?:[^"\\]|\\.)*)"', path.read_text()):
            if m.group(1) not in keys:
                keys.append(m.group(1))
    return keys


def escape(text):
    """A translation in .strings syntax. translations.json keeps .strings escapes (\\n) as
    they are, so only bare double quotes need escaping."""
    return re.sub(r'(?<!\\)"', '\\"', text)


def strings_line(key, value):
    # Keys are copied from Swift literals, so they're already escaped the way .strings wants
    # (\n, \", \\).
    return f'"{key}" = "{value}";\n'



def main():
    table = json.loads((ROOT / "Localization" / "translations.json").read_text())
    keys = source_keys()
    errors = []
    for key in keys:
        if key not in table:
            errors.append(f"missing translation: {key!r}")
            continue
        if unsupported(key):
            errors.append(f"unsupported format specifier: {key!r}")
        for lang in LANGUAGES:
            value = table[key].get(lang)
            if value and unsupported(value):
                errors.append(f"unsupported format specifier in {lang}: {value!r}")
            if not value:
                errors.append(f"missing {lang}: {key!r}")
            elif placeholders(value) != placeholders(key):
                errors.append(f"placeholders differ in {lang}: {key!r} -> {value!r}")
    unused = sorted(set(table) - set(keys))
    if errors:
        print("\n".join(errors), file=sys.stderr)
        sys.exit(1)

    header = "/* Generated by Localization/build-strings.py from translations.json; edit that file. */\n\n"
    for lang in ["en"] + LANGUAGES:
        folder = ROOT / "Resources" / f"{lang}.lproj"
        folder.mkdir(parents=True, exist_ok=True)
        lines = [strings_line(k, k if lang == "en" else escape(table[k][lang])) for k in keys]
        (folder / "Localizable.strings").write_text(header + "".join(lines))
    note = f" ({len(unused)} unused entries in translations.json)" if unused else ""
    print(f"Localized {len(keys)} strings into en, {', '.join(LANGUAGES)}{note}")


if __name__ == "__main__":
    main()
